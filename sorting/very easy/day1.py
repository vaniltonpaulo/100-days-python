def zip_it(women, men):
      if len(women) != len(men):
            return "sizes don't match"
      else:
            return list(zip(women, men))
      


Test.assert_equals(zip_it(["Elise", "Mary"], ["John", "Rick"]), [("Elise", "John"), ("Mary", "Rick")])
Test.assert_equals(zip_it(["Ana", "Amy", "Lisa"], ["Bob", "Josh"]), "sizes don't match")
