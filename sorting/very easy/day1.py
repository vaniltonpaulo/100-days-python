def age_difference(ages):
      if sorted(ages)[-1] != sorted(ages)[-2] :
            age = sorted(ages)[-1] - sorted(ages)[-2]
            if age > 1:
                  return str(age) + " years"
            else:
                  return str(age) + " year"
      
      else:
            return "No age difference between spouses."

Test.assert_equals(age_difference([29, 1, 6, 8, 28]), "1 year")
Test.assert_equals(age_difference([43, 86, 49, 86]), "No age difference between spouses.")
Test.assert_equals(age_difference([2, 4, 6, 32, 27]), "5 years")
Test.assert_equals(age_difference([55, 28, 25, 56, 20]), "1 year")
Test.assert_equals(age_difference([21, 56, 69, 18]), "13 years")
Test.assert_equals(age_difference([25, 70, 25, 26, 58]), "12 years")
Test.assert_equals(age_difference([10, 12, 44, 9, 44]), "No age difference between spouses.")
